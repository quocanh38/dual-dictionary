import assert from 'node:assert/strict';
import fs from 'node:fs';
import {readLibraryIndex,readLibraryPack,fetchLibraryPack,fetchLibraryIndex} from '../../lessons/library.js';
import {exportPack} from '../../lessons/schema.js';
const p=JSON.parse(fs.readFileSync(new URL('../../lessons/example.json',import.meta.url))),e=await exportPack(p);
const entry={packId:p.packId,version:p.version,title:p.title,topic:p.topic,levelEstimate:p.levelEstimate,file:'fixture.json',sha256:e.sha256};
const index={format:'dual-dictionary-lesson-library',schemaVersion:1,packs:[entry]};
assert.deepEqual(readLibraryIndex(JSON.stringify(index)),index);
assert.deepEqual(await readLibraryPack(JSON.stringify(e),entry),e);
for(const file of ['../secret.json','https://example.com/pack.json','p.json?key=x','a/b.json'])assert.throws(()=>readLibraryIndex(JSON.stringify({...index,packs:[{...entry,file}]})),/entry/);
assert.throws(()=>readLibraryIndex(JSON.stringify({...index,packs:[entry,entry]})),/Duplicate/);
await assert.rejects(readLibraryPack(JSON.stringify(e),{...entry,title:'Wrong title'}),/reviewed index/);
await assert.rejects(readLibraryPack(JSON.stringify(e),{...entry,sha256:'0'.repeat(64)}),/reviewed index/);
const tampered=structuredClone(e);tampered.payload.title+=' changed';await assert.rejects(readLibraryPack(JSON.stringify(tampered),entry),/Integrity/);
const draft=structuredClone(p);draft.review.status='draft';await assert.rejects(readLibraryPack(JSON.stringify({...e,payload:draft}),entry));
let calls=0;await assert.rejects(fetchLibraryPack({...entry,file:'../bad.json'},()=>{calls++;}),/entry/);assert.equal(calls,0);
await assert.rejects(fetchLibraryIndex(async()=>({ok:false})),/unavailable/);
await assert.rejects(fetchLibraryPack(entry,async()=>({ok:false})),/unavailable/);
assert.deepEqual(await fetchLibraryIndex(async()=>({ok:true,text:async()=>JSON.stringify(index)})),index);
console.log('PASS reviewed index, exact approved hash/metadata, tampering, draft rejection, local paths and explicit fetch failures; 0 provider calls');
