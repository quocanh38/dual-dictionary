export function summarizeLiveEvalResults(results, caseCount = LIVE_EVAL_CASES.length) {
  const rows = [...results.values()];
  const successes = rows.filter((item) => item.status === 'success');
  return {
    authoredCases: caseCount,
    casesAttempted: rows.length,
    providerCalls: rows.length,
    questions: rows.length,
    successfulResponses: successes.length,
    verdictScored: successes.length,
    verdictMatched: successes.filter((item) => item.expectedVerdictPass).length,
    quoteScored: rows.filter((item) => typeof item.quoteValid === 'boolean').length,
    quoteValid: rows.filter((item) => item.quoteValid === true).length,
    explanationQualityScored: rows.filter((item) => item.explanationQuality != null && item.explanationQuality !== '').length,
    latencySamples: rows.filter((item) => Number.isFinite(item.elapsedMs)).length,
    errors: rows.filter((item) => item.status === 'error').length,
    errorTypes: rows.filter((item) => item.status === 'error').map((item) => item.errorCategory),
  };
}
